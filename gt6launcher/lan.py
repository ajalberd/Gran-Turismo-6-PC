def _user_dir() -> str:
    return os.path.join(paths.rpcs3_config_dir(), "dev_hdd0", "home", "00000001")


def get_username() -> str:
    try:
        with open(os.path.join(_user_dir(), "localusername"), "r", encoding="utf-8") as f:
            return f.read().strip()
    except OSError:
        return ""


def set_username(name: str) -> None:
    name = re.sub(r"[^\w\-. ]", "", name)[:16] or "Player"
    os.makedirs(_user_dir(), exist_ok=True)
    with open(os.path.join(_user_dir(), "localusername"), "w", encoding="utf-8") as f:
        f.write(name)


def global_config_path() -> str:
    return os.path.join(paths.rpcs3_settings_dir(), "config.yml")


def get_psid() -> str:
    return str(load_cfg(global_config_path()).get("System", {}).get("Console PSID", ""))


def regenerate_psid() -> str:
    cfg = load_cfg(global_config_path())
    psid = "0x" + "".join(random.choice("0123456789ABCDEF") for _ in range(32))
    cfg.setdefault("System", {})["Console PSID"] = psid
    cfg["System"]["System Name"] = f"GT6-{socket.gethostname()[:10]}"
    atomic_write(global_config_path(), dump_cfg(cfg))
    return psid


def apply_global_network(enabled: bool, bind: str = "0.0.0.0") -> None:
    """The gist notes the network settings must be set globally as well."""
    cfg = load_cfg(global_config_path())
    net = cfg.setdefault("Net", {})
    net["Internet enabled"] = "Connected" if enabled else "Disconnected"
    net["PSN status"] = "Disconnected"
    net["Bind address"] = bind
    atomic_write(global_config_path(), dump_cfg(cfg))


def local_ips() -> list[str]:
    ips = set()
    try:
        s = socket.socket(socket.AF_INET, socket.SOCK_DGRAM)
        s.connect(("10.255.255.255", 1))
        ips.add(s.getsockname()[0])
        s.close()
    except OSError:
        pass
    try:
        for info in socket.getaddrinfo(socket.gethostname(), None, socket.AF_INET):
            ips.add(info[4][0])
    except OSError:
        pass
    return sorted(i for i in ips if not i.startswith("127."))


