# --------------------------------------------------------------------------- RPCN (online)
RPCN_SALT = b"No matter where you go, everybody's connected."


def rpcn_path() -> str:
    return os.path.join(paths.rpcs3_settings_dir(), "rpcn.yml")


def rpcn_get() -> dict:
    return load_cfg(rpcn_path())


def rpcn_set_login(npid: str, password: str, token: str = "") -> None:
    """Store an existing RPCN account exactly like RPCS3 does (rpcn_settings_dialog.cpp:
    PBKDF2-SHA3-256, 200000 rounds, fixed salt, upper-case hex)."""
    import hashlib
    cfg = rpcn_get()
    if not password and npid.strip() != str(cfg.get("NPID", "")):
        raise ValueError("Enter the password for the new RPCN user.")
    cfg.setdefault("Version", "2")
    cfg.setdefault("Host", "np.rpcs3.net")
    cfg.setdefault("Hosts", "Official RPCN Server|np.rpcs3.net")
    cfg["NPID"] = npid.strip()
    if password:
        cfg["Password"] = hashlib.pbkdf2_hmac("sha3_256", password.encode(), RPCN_SALT, 200_000).hex().upper()
    cfg["Token"] = token.strip()
    atomic_write(rpcn_path(), dump_cfg(cfg))
