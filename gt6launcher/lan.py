def firewall_active() -> bool:
    """True if a host firewall service is running (Windows: always, it asks on first use)."""
    if paths.IS_WINDOWS:
        return True
    import shutil
    import subprocess
    if not shutil.which("systemctl"):
        return False
    for unit in ("firewalld", "ufw", "nftables"):
        try:
            r = subprocess.run(["systemctl", "is-active", unit], capture_output=True, text=True, timeout=5)
            if r.stdout.strip() == "active":
                return True
        except (OSError, subprocess.SubprocessError):
            pass
    return False


